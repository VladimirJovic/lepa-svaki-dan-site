/* search.js: the site search. ONE engine for every page: the search overlay (header icon, hero bar on the home page) and the price-list
   filter of the home page. No dependencies. Pripremio ECHOSYSTEM-MOTHER AGENCY.

   DATA     assets/search-index.js (window.LSD_SEARCH, generated by _tools/b/build-pages.mjs from the price list, the 21 texts, the offers and
            _shared/content/search-synonyms.json). It is loaded the first time it is needed (hover/touch of a search button, opening the
            overlay, typing in the price-list filter) and on the home page also when the browser is idle.
   MATCHING lower case, diacritics ignored (c/c/s/z, dj for the d with stroke), partial words ("akn" finds "akne"), several words (all must
            match, filler words such as "kako" or "da" are skipped), simple inflection ("bore", "bora", "borama" are one word) and the
            hidden synonym vocabulary: women's own wording ("ozilci od akni", "kako smanjiti obim", "blistava koza") maps to the groups, services,
            texts and offers that really contain the topic. The vocabulary is never printed anywhere: no hashtags, no chips.
   RESULTS  grouped: Tretmani (by price-list category, each row = a price-list group with its from-price, linking to the group in the Cenovnik),
            Tekstovi (title + excerpt, link to the text page), Posebna ponuda. Keyboard: arrows, Enter, Escape. Count in an aria-live region.
   API      window.LSD.search = { load(), services(query), open(from, query), close() }                                                     */
