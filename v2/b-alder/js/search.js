  var SUF = ['ovima', 'evima', 'ama', 'ima', 'ove', 'ovi', 'eva', 'ova', 'ska', 'ske', 'ski', 'nih', 'om', 'em', 'og', 'oj', 'ih', 'im', 'ju', 'ja', 'je', 'ji', 'ca', 'ce', 'ci', 'a', 'e', 'i', 'o', 'u'];
  var stem = function (w) { for (var i = 0; i < SUF.length; i++) { var s = SUF[i]; if (w.length - s.length >= 3 && w.slice(-s.length) === s) return w.slice(0, -s.length); } return w; };
  var STOP = {}; 'a i u o da se li je su za na od do sa pa ili ali kao sta sto kako koji koja koje kada gde zasto mi me ti vi ja ima imam mogu moze treba hocu zelim mozete postoji uraditi uradim radi bih bi'.split(' ').forEach(function (w) { STOP[w] = 1; });
  var words = function (s) { return F(s).split(' ').filter(Boolean).map(function (w) { return { w: w, s: stem(w) }; }); };

  /* best score of one query token against a list of document words: 3 exact, 2 starts with it (typing), 1.4 same stem, .8 inside a long word */
  function best(tok, ws) {
    var ts = stem(tok), b = 0;
    for (var i = 0; i < ws.length; i++) {
      var o = ws[i], w = o.w, sc = 0;
      if (w === tok) sc = 3;
      else if (w.length > tok.length && w.indexOf(tok) === 0) sc = 2;
      else if (ts.length >= 3 && (o.s === ts || (ts.length >= 4 && w.indexOf(ts) === 0))) sc = 1.4;
      else if (tok.length >= 5 && w.indexOf(tok) > 0) sc = .8;
      if (sc > b) { b = sc; if (b === 3) break; }
    }
    return b;
  }
  /* every token has to match somewhere (best weighted field per token); 0 when one does not */
  function scoreFields(toks, fields) {
    var total = 0;
    for (var t = 0; t < toks.length; t++) {
      var b = 0;
      for (var f = 0; f < fields.length; f++) { var s = best(toks[t], fields[f].ws) * fields[f].k; if (s > b) b = s; }
      if (!b) return 0;
      total += b;
    }
    return total;
  }

