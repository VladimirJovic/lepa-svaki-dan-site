#!/usr/bin/env node
/* =====================================================================================================
   apply-final-site.js : the data of the FINAL SITE (preview A + parts of C), applied on top of content.json / content.js
   Pripremio ECHOSYSTEM-MOTHER AGENCY

   WHY THIS FILE EXISTS
   content.json is generated by build-content.js from the old site (and the texts pack adds the Word texts). The client feedback of October 2026
   (feedback 3) needs a few things that the old site never had. They are applied here, in ONE idempotent step, so that a regeneration keeps them:

       node _tools/build-content.js          (only if the pack is regenerated from the old site)
       node _tools/apply-final-site.js       (always last: founder, typo, second e-mail, strip, price-list notice, bestsellers)

   WHAT IT DOES (every item is a client wish, see _specs/feedback3/transkript.txt)
   - founder: Tamara Cosic, "osnivacica Lepe Svaki Dan", everywhere (founder.*, image alts, page description) via content-fixes.js (rules: content-fixes.rules.json);
     Tamara Vujacic is a doctor and keeps "dr" on the two price-list lines where she is named.
   - payment note: the typo "orjentacionog" becomes "orijentacionog" (content-fixes.rules.json, typos[]).
   - contact.emails[]: two phone / e-mail PAIRS (phone 1 + mail 1, phone 2 + mail 2). The SECOND MAIL IS NOT KNOWN YET: emails[1].email is null and the
     site shows pair 2 with the phone alone. Fill emails[1].email (and emailHref) when the client sends it, then rebuild: nothing else to change.
   - stats.items[]: the numbers of the info strip of the About section (value, suffix, display, label, icon). The hours of the strip are contact.hours.
     DROP TAMARA'S REAL NUMBERS HERE (and her hours in contact.hours), then rebuild: the strip is rendered from exactly these two places.
   - payment.popup: the strings of the one-time price-list notice (payment in dinars + the search reminder). PROVISIONAL, to be refined with Tamara.
   - sections.bestsellers + about.founderWord + sections.verticals.eyebrow: the new names of the About block and of the services section.
   Existing keys are never deleted; the gift list (gifts[]) stays in the pack, it is shown as "Bestseller tretmani" inside the About section.
   ===================================================================================================== */
'use strict';
const fs = require('fs');
const path = require('path');
const FX = require('./content-fixes.js');

const DIR = path.resolve(__dirname, '..');
const content = JSON.parse(fs.readFileSync(path.join(DIR, 'content.json'), 'utf8'));
const log = [];
const set = (obj, key, value, label) => {
  if (JSON.stringify(obj[key]) !== JSON.stringify(value)) { log.push(label + ': ' + (obj[key] === undefined ? '(new)' : 'changed')); obj[key] = value; }
};

/* 1. founder, typos, dashes (the reviewed rules) */
const fixLog = FX.applyFixes(content).filter((c) => c.before !== null);
fixLog.forEach((c) => log.push('fix ' + c.path));

/* 1b. the hero sentence of the published site (stage 1 of the final site: the line under "2 lokacije, 1 filozofija" reads as on lepasvakidan.rs).
       build-content.js still extracts the older sentence of the old preview, so it is set here; the footer repeats it word for word. */
set(content.hero, 'sub', 'Oaza lepote i uživanja na mestu koje spaja moderne aparaturne tretmane i estetske procedure sa klasičnom negom u cilju očuvanja lepote.', 'hero.sub');

/* 2. contact: two pairs (phone + mail). The second mail is not known: null = the site shows the phone alone. */
const c = content.contact;
set(c, 'emails', [
  { location: 'nb', label: 'Beauty Concept', email: c.email, emailHref: c.emailHref },
  { location: 'bw', label: 'Wellbeing Concept', email: null, emailHref: null,
    note: 'The second e-mail address is NOT known yet (client to send). Until emails[1].email is filled in, pair 2 shows its phone alone. Never invent an address.' },
], 'contact.emails');

/* 3. the info strip: numbers + labels (+ the icon of each). Hours of the strip = contact.hours. */
const ICONS = ['medal', 'pin', 'users'];
content.stats.items.forEach((it, i) => set(it, 'icon', ICONS[i], 'stats.items[' + i + '].icon'));
set(content.stats, 'note', 'The info strip of the About section is rendered from stats.items[] (value, suffix, display, label, icon) and from contact.hours (the hours chip). '
  + 'Drop the client\'s real statistics here and her working hours in contact.hours, then run _tools/a/build-pages.mjs. items[].display is what the counter shows when its count-up ends.', 'stats.note');

/* 4. the one-time notice that opens the first time a visitor reaches the price list (home only). PROVISIONAL copy: refine with Tamara.
      The payment paragraphs are NOT repeated here: they are payment.modal.paragraphs (the same text as the "Placanje u dinarima" chip). */
set(content.payment, 'popup', {
  title: 'Pre nego što pogledate cene',
  eyebrow: 'Cenovnik',
  paymentHeading: 'Plaćanje isključivo u dinarima',
  searchHeading: 'Pretražite sve usluge',
  searchText: 'Za pronalazak i lakše kretanje kroz sajt koristite pretragu: upišite bilo koju uslugu koju tražite, na primer „ožiljci od akni“ ili „kako smanjiti obim“.',
  searchButton: 'Pretraži',
  searchLink: 'Otvori pretragu celog sajta',
  okLabel: 'Razumem',
  closeAria: 'Zatvori',
  provisional: 'Provisional copy (client feedback 3, price list 1): to be refined with Tamara, together with the whole "Usluge i cene" section.',
}, 'payment.popup');

/* 5. names: About block, services section, bestsellers (the former gift section lives inside the About section) */
set(content.about, 'founderWord', {
  eyebrow: 'Reč osnivača i posebne pogodnosti',
  note: 'Text to be refined with Tamara (client feedback 3, about 2). The block holds the About copy, the founder quote (quote.*) and the signature (founder.signature).',
}, 'about.founderWord');
set(content.sections.verticals, 'eyebrow', 'Naše usluge', 'sections.verticals.eyebrow');
set(content.sections, 'bestsellers', {
  eyebrow: 'Naša preporuka tretmana za poklone',
  title: 'Bestseller tretmani',
  introFrom: 'sections.gifts.intro',
  note: 'Was the standalone section "Tretmani za poklon" (#poklon). Client feedback 3, about 2: it now sits under the photo of the About section as "Bestseller tretmani"; the items are gifts[] and link to their price-list rows.',
}, 'sections.bestsellers');

/* 6. notes for the owner of the data */
const W = content._meta.warnings;
[
  'Second e-mail address: contact.emails[1].email is null (the client still has to send it). Pair 2 of every contact line shows its phone alone until it is set.',
  'The testimonial of "Jovana M." says "Tamara" ("Posle prve konsultacije Tamara mi je dala plan ..."): placeholder client text, left as it is. Ask the client whom it names now that Tamara Ćosić (founder) and Tamara Vujačić (doctor) are two people.',
  'Payment note: "Banca Intesa" (modal) and "Banka Intesa" (price-list footer) are spelled differently in the old text: client to confirm one spelling.',
].forEach((w) => { if (!W.includes(w)) { W.push(w); log.push('warning added'); } });

/* write content.json and content.js (same header and shape as build-content.js) */
const json = FX.jsonNoDash(content, 2);
FX.assertClean(json, 'content.json');
fs.writeFileSync(path.join(DIR, 'content.json'), json + '\n');
const js = '/* Lepa Svaki Dan v2 content pack, generated by _tools/build-content.js (ECHOSYSTEM-MOTHER AGENCY). Works from file:// */\nwindow.LSD_CONTENT = ' + json + ';\n';
FX.assertClean(js, 'content.js');
fs.writeFileSync(path.join(DIR, 'content.js'), js);
console.log('content.json / content.js written. Changes: ' + (log.length ? '\n  ' + log.join('\n  ') : 'none (already up to date)'));
